"""Build qwen_chat_molab.py from the cell sources in dev/cells.

Each file in dev/cells is one marimo cell, in file-name order. An optional first line
`# @cell hide_code` (or `# @cell show_code`) sets the cell's code visibility; hide_code is the default.
marimo's own code generator works out each cell's inputs and outputs, so the cell files are plain Python.

Usage: python dev/build.py            (writes qwen_chat_molab.py next to dev/)
       python dev/build.py --check    (exits 1 if the notebook is out of date)
"""

import sys
from pathlib import Path

import marimo._ast.codegen as codegen
from marimo._ast.app_config import _AppConfig
from marimo._ast.cell import CellConfig

ROOT = Path(__file__).resolve().parent.parent
CELLS = ROOT / "dev" / "cells"
OUT = ROOT / "qwen_chat_molab.py"

HEADER = """# /// script
# requires-python = ">=3.11"
# dependencies = [
#     "marimo",
#     "anywidget==0.11.0",
#     "traitlets==5.16.1",
#     "playwright==1.65.2",
#     "numpy",
# ]
# [tool.marimo.display]
# theme = "dark"
# ///
# Generated by dev/build.py from dev/cells/*.py. Edit the cell files, then rebuild."""


def build():
    codes, configs = [], []
    for path in sorted(CELLS.glob("*.py")):
        text = path.read_text(encoding="utf-8")
        first, _, rest = text.partition("\n")
        hide = True
        if first.startswith("# @cell"):
            hide = "show_code" not in first
            text = rest
        codes.append(text.strip("\n"))
        configs.append(CellConfig(hide_code=hide))
    return codegen.generate_filecontents(
        codes,
        ["_"] * len(codes),
        configs,
        config=_AppConfig(width="full", app_title="Qwen Chat RP", auto_download=["html"]),
        header_comments=HEADER,
    )


if __name__ == "__main__":
    content = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        sys.exit(0 if current == content else 1)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.name}: {content.count(chr(10))} lines, {len(list(CELLS.glob('*.py')))} cells")
